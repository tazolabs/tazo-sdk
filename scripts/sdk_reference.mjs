// Convert Sphinx JSON to checked-in Mintlify pages, avoiding hosted SDK conversion.
import { generateSdkReference } from '@mintlify/scraping';
import { mkdir, readFile, readdir, unlink, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const [source, mode] = process.argv.slice(2);
if (!source) throw new Error('Pass the Sphinx JSON directory');
const destination = fileURLToPath(new URL('../docs/mintlify/reference/', import.meta.url));
const prefix = '/sdk/python/reference/';
const { pages } = await generateSdkReference('sphinx', source);
const slugs = new Set(pages.map((page) => page.slug));
const expected = new Map(pages.map((page) => {
  const content = page.content.replace(/\]\(\/([^\s)]+)\)/g, (match, target) => {
    const [slug] = target.split('#');
    return slugs.has(slug) ? `](${prefix}${target})` : match;
  });
  return [`${page.slug}.mdx`, [
    '---',
    `title: ${JSON.stringify(page.title)}`,
    ...(page.description ? [`description: ${JSON.stringify(page.description)}`] : []),
    '---',
    '',
    '{/* Generated by scripts/sdk_reference.py. Edit the SDK or its Sphinx sources. */}',
    '',
    content.trim(),
    '',
  ].join('\n')];
}));

if (mode === '--check') {
  const files = (await readdir(destination)).filter((file) => file.endsWith('.mdx'));
  if (files.length !== expected.size || files.some((file) => !expected.has(file))) {
    throw new Error('SDK reference pages are stale; run python scripts/sdk_reference.py');
  }
  for (const [name, content] of expected) {
    if (await readFile(path.join(destination, name), 'utf8') !== content) {
      throw new Error(`SDK reference ${name} is stale; run python scripts/sdk_reference.py`);
    }
  }
} else {
  await mkdir(destination, { recursive: true });
  for (const name of await readdir(destination)) {
    if (name.endsWith('.mdx') && !expected.has(name)) {
      await unlink(path.join(destination, name));
    }
  }
  for (const [name, content] of expected) {
    await writeFile(path.join(destination, name), content);
  }
}
